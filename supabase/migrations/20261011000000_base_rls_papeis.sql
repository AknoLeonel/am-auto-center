-- Fase 0: esquema base (idempotente), papéis de acesso e RLS em todas as tabelas.
-- Seguro para rodar sobre o banco existente: só cria o que falta e recria as policies.

-- ============ Tabelas ============
create table if not exists public.clientes (
  id uuid primary key default gen_random_uuid(),
  nome text not null,
  telefone text,
  criado_em timestamptz not null default now()
);

create table if not exists public.veiculos (
  id uuid primary key default gen_random_uuid(),
  cliente_id uuid not null references public.clientes(id) on delete cascade,
  placa text not null unique,
  tipo text not null default 'carro',
  modelo text,
  ano int,
  km int,
  criado_em timestamptz not null default now()
);

create table if not exists public.ordens_servico (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity,
  cliente_id uuid not null references public.clientes(id) on delete restrict,
  veiculo_id uuid not null references public.veiculos(id) on delete restrict,
  status text not null default 'aguardando',
  defeito text,
  km int,
  observacoes text,
  criado_em timestamptz not null default now(),
  concluido_em timestamptz
);

create table if not exists public.os_itens (
  id uuid primary key default gen_random_uuid(),
  os_id uuid not null references public.ordens_servico(id) on delete cascade,
  tipo text not null default 'servico',
  descricao text not null,
  qtd numeric not null default 1,
  valor_unit numeric not null default 0
);

create table if not exists public.lembretes (
  id uuid primary key default gen_random_uuid(),
  cliente_id uuid not null references public.clientes(id) on delete cascade,
  veiculo_id uuid references public.veiculos(id) on delete cascade,
  os_id uuid references public.ordens_servico(id) on delete cascade,
  motivo text not null,
  data_aviso date not null,
  enviado boolean not null default false,
  criado_em timestamptz not null default now()
);

create table if not exists public.pedidos_site (
  id uuid primary key default gen_random_uuid(),
  tipo text not null,
  nome text,
  telefone text,
  veiculo text,
  mensagem text not null,
  status text not null default 'novo',
  criado_em timestamptz not null default now()
);

-- ============ Índices (chaves estrangeiras e filtros do painel) ============
create index if not exists veiculos_cliente_idx on public.veiculos (cliente_id);
create index if not exists os_veiculo_idx on public.ordens_servico (veiculo_id);
create index if not exists os_cliente_idx on public.ordens_servico (cliente_id);
create index if not exists os_status_criado_idx on public.ordens_servico (status, criado_em desc);
create index if not exists os_criado_idx on public.ordens_servico (criado_em desc);
create index if not exists os_itens_os_idx on public.os_itens (os_id);
create index if not exists lembretes_pendentes_idx on public.lembretes (data_aviso) where not enviado;
create index if not exists lembretes_os_idx on public.lembretes (os_id);
create index if not exists pedidos_status_criado_idx on public.pedidos_site (status, criado_em desc);

-- ============ Regras de integridade ============
do $$ begin
  alter table public.ordens_servico add constraint os_status_chk
    check (status in ('aguardando','diagnostico','aprovacao','em_servico','pronto','entregue','cancelada')) not valid;
exception when duplicate_object then null; end $$;

do $$ begin
  alter table public.pedidos_site add constraint pedidos_tipo_chk check (tipo in ('pecas','guincho','orcamento')) not valid;
exception when duplicate_object then null; end $$;
do $$ begin
  alter table public.pedidos_site add constraint pedidos_status_chk
    check (status in ('novo','em_atendimento','concluido','descartado')) not valid;
exception when duplicate_object then null; end $$;
do $$ begin
  alter table public.pedidos_site add constraint pedidos_tamanho_chk check (
    char_length(mensagem) <= 1800 and char_length(coalesce(nome,'')) <= 120
    and char_length(coalesce(veiculo,'')) <= 120 and char_length(coalesce(telefone,'')) <= 20
  ) not valid;
exception when duplicate_object then null; end $$;

-- ============ Papéis ============
create table if not exists public.perfis (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nome text,
  papel text not null default 'mecanico' check (papel in ('dono','atendente','mecanico')),
  ativo boolean not null default true,
  criado_em timestamptz not null default now()
);

-- Quem já tinha acesso ao painel antes desta migration vira 'dono' (a oficina começou com uma conta de gestão).
-- Novos usuários entram como 'mecanico' (menor privilégio) e o dono promove quando necessário.
insert into public.perfis (user_id, nome, papel)
select id, split_part(email, '@', 1), 'dono' from auth.users
on conflict (user_id) do nothing;

create or replace function public.criar_perfil_novo_usuario() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.perfis (user_id, nome) values (new.id, split_part(new.email, '@', 1))
  on conflict (user_id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.criar_perfil_novo_usuario();

-- Papel do usuário logado (nulo se não existir ou estiver inativo). Usado nas policies.
create or replace function public.papel_atual() returns text
language sql stable security definer set search_path = '' as $$
  select papel from public.perfis where user_id = (select auth.uid()) and ativo
$$;
revoke all on function public.papel_atual() from public, anon;
grant execute on function public.papel_atual() to authenticated;

-- ============ RLS ============
alter table public.clientes enable row level security;
alter table public.veiculos enable row level security;
alter table public.ordens_servico enable row level security;
alter table public.os_itens enable row level security;
alter table public.lembretes enable row level security;
alter table public.pedidos_site enable row level security;
alter table public.perfis enable row level security;

-- Recria as policies do zero (remove qualquer policy antiga mais permissiva).
do $$ declare r record; begin
  for r in select schemaname, tablename, policyname from pg_policies
           where schemaname = 'public'
             and tablename in ('clientes','veiculos','ordens_servico','os_itens','lembretes','pedidos_site','perfis')
  loop
    execute format('drop policy %I on %I.%I', r.policyname, r.schemaname, r.tablename);
  end loop;
end $$;

-- Tabelas operacionais: equipe ativa lê e escreve; apagar fica com dono e atendente.
do $$ declare t text; begin
  foreach t in array array['clientes','veiculos','ordens_servico','os_itens','lembretes'] loop
    execute format('create policy "equipe le" on public.%I for select to authenticated using (public.papel_atual() is not null)', t);
    execute format('create policy "equipe insere" on public.%I for insert to authenticated with check (public.papel_atual() is not null)', t);
    execute format('create policy "equipe altera" on public.%I for update to authenticated using (public.papel_atual() is not null) with check (public.papel_atual() is not null)', t);
    execute format('create policy "gestao apaga" on public.%I for delete to authenticated using (public.papel_atual() in (''dono'',''atendente''))', t);
  end loop;
end $$;

-- Pedidos do site: o público só envia (sempre como 'novo'); a equipe gerencia.
create policy "publico envia pedido" on public.pedidos_site for insert to anon, authenticated
  with check (status = 'novo');
create policy "equipe le pedidos" on public.pedidos_site for select to authenticated
  using (public.papel_atual() is not null);
create policy "equipe altera pedidos" on public.pedidos_site for update to authenticated
  using (public.papel_atual() is not null) with check (public.papel_atual() is not null);
create policy "gestao apaga pedidos" on public.pedidos_site for delete to authenticated
  using (public.papel_atual() in ('dono','atendente'));

-- Perfis: cada um vê o próprio; o dono vê e gerencia todos.
create policy "ve proprio perfil" on public.perfis for select to authenticated
  using (user_id = (select auth.uid()) or public.papel_atual() = 'dono');
create policy "dono gerencia perfis" on public.perfis for update to authenticated
  using (public.papel_atual() = 'dono') with check (public.papel_atual() = 'dono');

-- ============ Privilégios de tabela ============
revoke all on all tables in schema public from anon;
grant insert on public.pedidos_site to anon;
grant select, insert, update, delete on public.clientes, public.veiculos, public.ordens_servico,
  public.os_itens, public.lembretes, public.pedidos_site to authenticated;
grant select, update on public.perfis to authenticated;
